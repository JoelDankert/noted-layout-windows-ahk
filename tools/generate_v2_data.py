#!/usr/bin/env python3
"""Generate AutoHotkey v2 data from the preserved v1 declarative sources."""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "neo-ahk/source"
OUT = SRC / "v2-generated-data.ahk"


def fields(text):
    return [part.strip() for part in next(csv.reader([text], skipinitialspace=True, quotechar='"'))]


def ahk_string(value):
    return '"' + value.replace('`', '``').replace('"', '`"') + '"'


def encoded(value):
    if re.fullmatch(r"U[0-9A-Fa-f]{6}", value):
        codepoint = int(value[1:], 16)
        controls = {8: "S__Back", 9: "S___Tab", 13: "S__Entr", 27: "S____Esc"}
        return controls.get(codepoint, chr(codepoint))
    return value


key_text = (SRC / "keydefinitions.ahk").read_text(encoding="utf-8-sig")
key_text = key_text.split("neo20layoutstring :=", 1)[0] + key_text.split("; Numpad", 1)[1].split("; Die Modifier", 1)[0]
keys = []
variant = []
for line in key_text.splitlines():
    m = re.match(r'\s*(EDSK|EDS|EDNS|ED1)\((.*)\)\s*(?:;.*)?$', line)
    if not m:
        continue
    kind, raw = m.groups()
    row = fields(raw)
    if kind in ("EDS", "EDSK"):
        sc, caps, *levels = row
        levels += [""] * (8 - len(levels))
        keys.append(("sc" + sc, int(caps), list(map(encoded, levels[:8]))))
        if kind == "EDSK":
            variant.append((sc, int(caps), *map(encoded, (levels[0], levels[1], levels[4], levels[5]))))
    elif kind == "ED1":
        name, value = row
        keys.append((name, 0, [encoded(value)] * 8))
    elif kind == "EDNS":
        sc, caps, e1, e2, e3, e4a, e4b, e5, e6, *rest = row
        e7 = rest[0] if rest else ""
        e8 = rest[1] if len(rest) > 1 else ""
        keys.append(("sc" + sc, int(caps), list(map(encoded, [e1,e2,e3,e4a,e5,e6,e7,e8]))))

compose_text = (SRC / "compose.generated.ahk").read_text(encoding="utf-8-sig")
prefixes = set()
exact = {}
for line in compose_text.splitlines():
    m = re.match(r'\s*CM([^:]+):=1\s*$', line)
    if m:
        prefixes.add(m.group(1))
        continue
    m = re.match(r'\s*CD([^:]+):="([^"]*)"\s*$', line)
    if m:
        exact[m.group(1)] = m.group(2)

lines = [
    "; Generated by tools/generate_v2_data.py from the preserved GPL v1 data.",
    "BuildNeoData() {",
    "    data := Map()",
]
for key, caps, levels in keys:
    args = ", ".join(ahk_string(x) for x in levels)
    lines.append(f"    data[{ahk_string(key)}] := [{caps}, {args}]")
lines += ["    return data", "}", "", "BuildVariantMetadata() {", "    data := []"]
for row in variant:
    lines.append("    data.Push([" + ", ".join(ahk_string(str(x)) for x in row) + "])")
lines += ["    return data", "}", "", "BuildComposeData() {", "    prefixes := Map()"]
for key in sorted(prefixes):
    lines.append(f"    prefixes[{ahk_string(key)}] := true")
lines.append("    exact := Map()")
for key, value in sorted(exact.items()):
    lines.append(f"    exact[{ahk_string(key)}] := {ahk_string(value)}")
lines += ["    return [prefixes, exact]", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8-sig")
print(f"wrote {OUT}: {len(keys)} keys, {len(prefixes)} prefixes, {len(exact)} compose results")
